"""Streamlit triage prototype for the Network Intrusion Detection Prototype.

Thin UI layer over `src/predict.py` using the pre-trained Stage 2 model artifact
(`models/model.joblib`). Never retrains inside the application.

Launch locally:
    streamlit run app/app.py
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path
from typing import Any

import pandas as pd
import streamlit as st

# Ensure repository root is importable when launched via `streamlit run app/app.py`
ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src.config import (
    DEFAULT_DECISION_THRESHOLD,
    DEFAULT_MODEL_PATH,
    FEATURE_COLUMNS,
    FIGURES_DIR,
    RESULTS_DIR,
    SAMPLE_FILE,
)
from src.predict import (
    LABEL_ATTACK,
    load_model,
    predict_csv,
    predict_dataframe,
    predict_single_record,
)

KEY_DISPLAY_FEATURES: list[str] = [
    "protocol_type",
    "service",
    "flag",
    "duration",
    "src_bytes",
    "dst_bytes",
    "logged_in",
    "count",
    "srv_count",
    "serror_rate",
    "rerror_rate",
    "same_srv_rate",
    "dst_host_count",
    "dst_host_srv_count",
]


@st.cache_resource
def get_cached_model() -> Any:
    """Load and cache the pre-trained scikit-learn Pipeline."""
    return load_model(DEFAULT_MODEL_PATH)


@st.cache_data
def get_sample_data() -> pd.DataFrame:
    """Load and cache the 100-row NSL-KDD demo sample CSV."""
    return pd.read_csv(SAMPLE_FILE)


@st.cache_data
def get_model_metadata() -> dict[str, Any]:
    """Load Stage 2 model metadata JSON generated by `python -m src.train`."""
    meta_path = RESULTS_DIR / "model_metadata.json"
    if not meta_path.exists():
        return {}
    return json.loads(meta_path.read_text(encoding="utf-8"))


@st.cache_data
def get_result_csv(filename: str) -> pd.DataFrame:
    """Load a Stage 2 evaluation CSV from `reports/results/` if present."""
    path = RESULTS_DIR / filename
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


def render_disclaimer() -> None:
    """Render the mandatory safety and scope disclaimer banner."""
    st.warning(
        "**Research Prototype Disclaimer:** This application is a classroom research "
        "prototype trained on the historical **1998-era NSL-KDD benchmark dataset**. "
        "It is **not** a production Intrusion Detection or Prevention System (IDS/IPS) "
        "and must **never** be used to automatically block network traffic, penalize "
        "individuals, or make autonomous security decisions without human analyst review.",
        icon="⚠️",
    )


def render_sidebar(metadata: dict[str, Any]) -> float:
    """Render sidebar threshold controls and compact Stage 2 model summary."""
    st.sidebar.header("Triage Controls")
    threshold = st.sidebar.slider(
        label="Alert Decision Threshold",
        min_value=0.05,
        max_value=0.95,
        value=float(DEFAULT_DECISION_THRESHOLD),
        step=0.05,
        help=(
            "Connections with predicted attack probability >= threshold are flagged "
            "as Suspicious (Attack)."
        ),
    )

    st.sidebar.markdown(
        """
        **Recall vs. False-Alarm Trade-Off**
        - **Lower threshold (e.g., 0.10–0.30):** Catches more unseen or stealthy attacks
          (*higher recall*), but generates more alerts for analysts to review.
        - **Higher threshold (e.g., 0.50–0.80):** Reduces false alarms (*higher precision*),
          but risks missing novel or subtle intrusions.
        """
    )

    st.sidebar.divider()
    st.sidebar.subheader("Loaded Model Artifact")
    if metadata:
        st.sidebar.markdown(
            f"- **Experiment:** `{metadata.get('selected_experiment', 'E4')}`\n"
            f"- **Model:** {metadata.get('selected_model_name', 'Tuned Random Forest')}\n"
            f"- **Artifact Size:** `{metadata.get('model_size_mb', 'N/A')} MB`\n"
            f"- **Random Seed:** `{metadata.get('random_seed', 42)}`"
        )
        test_entries = metadata.get("test_metrics", [])
        e4_test = next((m for m in test_entries if m.get("id") == "E4"), None)
        if e4_test:
            st.sidebar.markdown(
                f"- **KDDTest+ ROC-AUC:** `{e4_test.get('test_roc_auc', 0):.4f}`\n"
                f"- **KDDTest+ Recall @ 0.50:** `{e4_test.get('test_recall', 0):.1%}`\n"
                f"- **KDDTest+ FPR @ 0.50:** `{e4_test.get('test_false_alarm_rate', 0):.1%}`"
            )
    else:
        st.sidebar.info("Model metadata file not found in `reports/results/`.")

    return float(threshold)


def render_sample_explorer(model: Any, sample_df: pd.DataFrame, threshold: float) -> None:
    """Mode 1: Explore and score single connection records or the full 100-row sample."""
    st.subheader("Sample Connection Explorer")
    st.write(
        "Inspect a connection record from `data/sample/sample_connections.csv` (100 rows, "
        "41 verified NSL-KDD features) and observe how the alert decision responds to "
        "the sidebar threshold."
    )

    if "sample_row_idx" not in st.session_state:
        st.session_state.sample_row_idx = 0

    col_btn, col_picker, col_spacer = st.columns([1.2, 1.5, 2.3])
    with col_btn:
        if st.button("Load Random Connection", use_container_width=True, type="primary"):
            st.session_state.sample_row_idx = random.randint(0, len(sample_df) - 1)
    with col_picker:
        selected_idx = st.number_input(
            "Or select sample row index",
            min_value=0,
            max_value=len(sample_df) - 1,
            value=int(st.session_state.sample_row_idx),
            step=1,
            label_visibility="collapsed",
        )
        st.session_state.sample_row_idx = int(selected_idx)
    with col_spacer:
        st.caption(
            f"Showing sample row **#{st.session_state.sample_row_idx}** of {len(sample_df)} records."
        )

    record_series = sample_df.iloc[st.session_state.sample_row_idx]
    record_dict = record_series.to_dict()

    try:
        outcome = predict_single_record(record_dict, model=model, threshold=threshold)
    except (ValueError, RuntimeError) as exc:
        st.error(f"Could not score sample record: {exc}")
        return

    prob = outcome["attack_probability"]
    pred_label = outcome["prediction"]
    is_attack = pred_label == LABEL_ATTACK

    m1, m2, m3 = st.columns(3)
    m1.metric("Predicted Class", pred_label)
    m2.metric("Attack Probability", f"{prob:.2%}")
    m3.metric("Active Threshold", f"{threshold:.2f}")

    st.progress(min(max(prob, 0.0), 1.0), text=f"Attack risk score: {prob:.2%} (cutoff {threshold:.0%})")

    if is_attack:
        st.error(
            f"Flagged for analyst triage: attack probability ({prob:.2%}) meets or exceeds "
            f"the active threshold ({threshold:.2f})."
        )
    else:
        st.success(
            f"Classified as Normal: attack probability ({prob:.2%}) is below the active "
            f"threshold ({threshold:.2f})."
        )

    st.markdown("#### Key Connection Attributes")
    key_df = pd.DataFrame(
        {
            "Feature": KEY_DISPLAY_FEATURES,
            "Value": [record_dict[col] for col in KEY_DISPLAY_FEATURES],
        }
    )
    st.dataframe(key_df, use_container_width=True, hide_index=True)

    with st.expander("View all 41 NSL-KDD features for this connection"):
        all_df = pd.DataFrame(
            {
                "Feature": FEATURE_COLUMNS,
                "Value": [record_dict[col] for col in FEATURE_COLUMNS],
            }
        )
        st.dataframe(all_df, use_container_width=True, hide_index=True)

    st.divider()
    with st.expander("Score all 100 sample records at the current threshold"):
        sample_scored = predict_dataframe(sample_df, model=model, threshold=threshold)
        flagged_count = int((sample_scored["predicted_label"] == 1).sum())
        st.caption(
            f"At threshold **{threshold:.2f}**, **{flagged_count} / {len(sample_scored)}** "
            f"sample connections ({flagged_count / len(sample_scored):.1%}) are flagged for review."
        )
        preview_cols = [
            "prediction",
            "attack_probability",
            "protocol_type",
            "service",
            "flag",
            "src_bytes",
            "dst_bytes",
            "count",
            "serror_rate",
        ]
        st.dataframe(
            sample_scored[preview_cols].sort_values("attack_probability", ascending=False),
            use_container_width=True,
        )


def render_csv_upload(model: Any, sample_df: pd.DataFrame, threshold: float) -> None:
    """Mode 2: Batch CSV upload, validation, flagged-row triage, and export."""
    st.subheader("Upload CSV for Batch Triage")
    st.write(
        "Upload a CSV file containing the **41 NSL-KDD feature columns** (optional "
        "`attack_type` and `difficulty` metadata columns are automatically ignored). "
        "Invalid files produce a readable validation message."
    )

    template_csv = sample_df.to_csv(index=False).encode("utf-8")
    dl_col, opt_col = st.columns([1.4, 2.6])
    with dl_col:
        st.download_button(
            label="Download Sample CSV Template (100 rows)",
            data=template_csv,
            file_name="sample_connections.csv",
            mime="text/csv",
            use_container_width=True,
        )
    with opt_col:
        has_header = st.checkbox(
            "Uploaded CSV includes a header row",
            value=True,
            help="Uncheck only if uploading a headerless raw NSL-KDD TXT/CSV file (41 or 43 columns).",
        )

    uploaded_file = st.file_uploader(
        "Choose a CSV or TXT file of network connection records",
        type=["csv", "txt"],
    )

    if uploaded_file is None:
        st.info(
            "Upload a connection log CSV above, or download the 100-row template first "
            "to try batch scoring."
        )
        return

    try:
        scored_df = predict_csv(
            uploaded_file,
            model=model,
            threshold=threshold,
            has_header=has_header,
        )
    except (FileNotFoundError, ValueError, RuntimeError) as exc:
        st.error(f"Input validation failed: {exc}")
        return
    except Exception as exc:
        st.error(f"Unexpected error while processing uploaded file: {exc}")
        return

    total_rows = len(scored_df)
    flagged_df = scored_df[scored_df["predicted_label"] == 1].sort_values(
        by="attack_probability", ascending=False
    )
    flagged_count = len(flagged_df)
    normal_count = total_rows - flagged_count
    alert_rate = (flagged_count / total_rows) if total_rows > 0 else 0.0

    k1, k2, k3, k4 = st.columns(4)
    k1.metric("Total Connections", f"{total_rows:,}")
    k2.metric("Flagged Suspicious", f"{flagged_count:,}")
    k3.metric("Normal", f"{normal_count:,}")
    k4.metric("Alert Rate", f"{alert_rate:.1%}")

    st.markdown("#### Flagged Suspicious Connections (Sorted by Attack Probability)")
    if flagged_df.empty:
        st.success(
            f"No connections met or exceeded the active alert threshold ({threshold:.2f})."
        )
    else:
        f_col1, f_col2 = st.columns(2)
        protocols = sorted(flagged_df["protocol_type"].dropna().astype(str).unique().tolist())
        services = sorted(flagged_df["service"].dropna().astype(str).unique().tolist())
        with f_col1:
            selected_protocols = st.multiselect(
                "Filter flagged rows by protocol",
                options=protocols,
                default=protocols,
            )
        with f_col2:
            selected_services = st.multiselect(
                "Filter flagged rows by service (optional)",
                options=services,
                default=[],
            )

        filtered_flagged = flagged_df.copy()
        if selected_protocols:
            filtered_flagged = filtered_flagged[
                filtered_flagged["protocol_type"].astype(str).isin(selected_protocols)
            ]
        if selected_services:
            filtered_flagged = filtered_flagged[
                filtered_flagged["service"].astype(str).isin(selected_services)
            ]

        display_cols = [
            "prediction",
            "attack_probability",
            "protocol_type",
            "service",
            "flag",
            "duration",
            "src_bytes",
            "dst_bytes",
            "count",
            "serror_rate",
            "dst_host_count",
        ]
        st.caption(f"Showing **{len(filtered_flagged):,}** of {flagged_count:,} flagged row(s).")
        st.dataframe(filtered_flagged[display_cols], use_container_width=True)

    with st.expander(f"Full Scored Results Preview (first {min(total_rows, 200)} rows)"):
        st.dataframe(scored_df.head(200), use_container_width=True)

    output_csv = scored_df.to_csv(index=False).encode("utf-8")
    st.download_button(
        label="Download Predictions CSV",
        data=output_csv,
        file_name=f"nids_predictions_thr_{threshold:.2f}.csv",
        mime="text/csv",
        type="primary",
    )


def render_benchmark_summary(metadata: dict[str, Any]) -> None:
    """Display real Stage 2 validation and KDDTest+ benchmark results."""
    st.subheader("Stage 2 Model & Benchmark Evaluation Summary")
    st.write(
        "All metrics below are loaded directly from `reports/results/` generated by "
        "`python -m src.train` on the official NSL-KDD train/test split."
    )

    exp_df = get_result_csv("experiments.csv")
    test_df = get_result_csv("test_evaluation.csv")
    thr_df = get_result_csv("test_threshold_tradeoff.csv")
    seen_df = get_result_csv("test_seen_vs_unseen.csv")

    if not exp_df.empty:
        st.markdown("#### 1. Validation Experiments (E1–E4 on 20% Stratified `KDDTrain+`)")
        st.dataframe(exp_df, use_container_width=True, hide_index=True)

    if not test_df.empty:
        st.markdown("#### 2. Held-Out Official `KDDTest+` Evaluation (Default Threshold `0.50`)")
        st.dataframe(test_df, use_container_width=True, hide_index=True)

    if not seen_df.empty:
        st.markdown("#### 3. Seen vs. Unseen Attack Generalization Gap (`E4` @ `0.50`)")
        st.dataframe(seen_df, use_container_width=True, hide_index=True)
        st.info(
            "Validation recall is 99.83%, while default-threshold `KDDTest+` recall is "
            "60.38% because `KDDTest+` introduces 17 unseen attack labels (20.40% recall at 0.50). "
            "However, E4's `KDDTest+` ROC-AUC is **0.9652**, so lowering the alert threshold "
            "raises recall substantially."
        )

    if not thr_df.empty:
        st.markdown("#### 4. `KDDTest+` Threshold Trade-Off (`E4`)")
        st.dataframe(thr_df, use_container_width=True, hide_index=True)

    if metadata.get("success_criteria"):
        sc = metadata["success_criteria"]
        st.markdown("#### 5. Honest Proposal Success Criteria Check")
        c1, c2 = st.columns(2)
        c1.metric(
            "KDDTest+ Attack Recall @ 0.50 (Target >= 0.80)",
            f"{sc.get('achieved_test_attack_recall', 0):.4f}",
            delta="Met @ threshold 0.10 (0.8460)" if not sc.get("recall_criterion_met") else "Met",
            delta_color="off",
        )
        c2.metric(
            "Validation Macro F1 Gain vs. E1 (Target >= +0.02)",
            f"+{sc.get('achieved_val_macro_f1_gain', 0):.4f}",
            delta=f"KDDTest+ gain @ 0.50: +{sc.get('achieved_test_macro_f1_gain', 0):.4f}",
            delta_color="off",
        )

    fig_cols = st.columns(2)
    cm_fig = FIGURES_DIR / "08_confusion_matrix_final_test.png"
    thr_fig = FIGURES_DIR / "10_threshold_tradeoff_test.png"
    if cm_fig.exists():
        fig_cols[0].image(str(cm_fig), caption="E4 Confusion Matrix on Official KDDTest+")
    if thr_fig.exists():
        fig_cols[1].image(str(thr_fig), caption="E4 Recall vs. False-Alarm Trade-Off on KDDTest+")


def main() -> None:
    """Entry point for the Streamlit triage application."""
    st.set_page_config(
        page_title="Network Intrusion Detection Prototype",
        page_icon="🛡️",
        layout="wide",
    )

    st.title("Network Intrusion Detection Prototype")
    st.caption(
        "Interactive ML triage assistant trained on NSL-KDD (E4 Tuned Random Forest) — "
        "CUSIT Programming for AI (Fall 2026)"
    )

    render_disclaimer()

    metadata = get_model_metadata()
    threshold = render_sidebar(metadata)

    try:
        model = get_cached_model()
    except (FileNotFoundError, RuntimeError) as exc:
        st.error(f"Unable to initialize model: {exc}")
        st.stop()

    try:
        sample_df = get_sample_data()
    except Exception as exc:
        st.error(f"Unable to load sample data from '{SAMPLE_FILE}': {exc}")
        st.stop()

    tab_sample, tab_upload, tab_benchmark = st.tabs(
        [
            "Sample Record Explorer",
            "Upload CSV for Batch Triage",
            "Model & Benchmark Summary",
        ]
    )

    with tab_sample:
        render_sample_explorer(model=model, sample_df=sample_df, threshold=threshold)

    with tab_upload:
        render_csv_upload(model=model, sample_df=sample_df, threshold=threshold)

    with tab_benchmark:
        render_benchmark_summary(metadata=metadata)


if __name__ == "__main__":
    main()
